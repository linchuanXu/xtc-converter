function t(key) {
    var lang = i18n[window.currentLang] || i18n.en;
    return lang[key] != null ? lang[key] : (i18n.en[key] || key);
}

function setLang(lang) {
    window.currentLang = lang;
    try { localStorage.setItem('lang', lang); } catch (e) {}
    if (document.documentElement) {
        document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    }
    updateAllText();
}

function updateAllText() {
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        var key = el.getAttribute('data-i18n');
        var val = t(key);
        if (el.getAttribute('data-i18n-placeholder') === 'true') {
            el.placeholder = val;
        } else if (el.tagName === 'OPTGROUP') {
            el.label = val;
        } else if (el.tagName === 'OPTION') {
            el.textContent = val;
        } else {
            el.textContent = val;
        }
    });
    document.title = t('appTitle');
    if (document.documentElement) {
        document.documentElement.lang = window.currentLang === 'zh' ? 'zh-CN' : 'en';
    }
    if (pageInfo) {
        if (typeof window.setPageInfoText === 'function') {
            window.setPageInfoText(typeof currentPage !== 'undefined' ? currentPage + 1 : 1, typeof totalPages !== 'undefined' ? totalPages : 0);
        } else {
            pageInfo.textContent = t('pageOf').replace('{0}', String(typeof currentPage !== 'undefined' ? currentPage + 1 : 1)).replace('{1}', String(typeof totalPages !== 'undefined' ? totalPages : 0));
        }
    }
    document.querySelectorAll('.lang-btn').forEach(function(btn) {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === window.currentLang);
    });
    document.querySelectorAll('.lang-toggle').forEach(function(btn) {
        btn.setAttribute('data-lang', window.currentLang);
        btn.textContent = window.currentLang === 'zh' ? '中/EN' : 'EN/中';
    });
    if (typeof window.updateFontModeHint === 'function') {
        window.updateFontModeHint();
    }
}
